"""Reusable manifold product-detail geometry, independent of Blender and Pydantic.

All dimensional parameters are meters. The rounded box has *real* bevel
geometry (not a renderer-only bevel modifier), and the four panel-frame rails
meet at mathematically defined miter joints.
"""

from __future__ import annotations

import math

from .architecture_geometry import (GeometryError, Mesh, Vec3, extrude_profile)


def rounded_box_mesh(size_m: tuple[float, float, float], corner_radius_m: float,
                     *, corner_segments: int = 5) -> Mesh:
    """Produce a welded, closed filleted box with spherical corner patches.

    Each face is sampled near its four edges and projected onto the Minkowski
    sum of an inner rectangular box and a sphere. The six grids share welded
    boundary vertices; no booleans, Blender modifiers, or loose faces remain.
    """
    if (len(size_m) != 3 or any(not math.isfinite(v) or v <= 0 for v in size_m) or
            not math.isfinite(corner_radius_m) or corner_radius_m <= 0 or
            corner_radius_m >= min(size_m) / 2 or
            type(corner_segments) is not int or not 2 <= corner_segments <= 12):
        raise GeometryError("Rounded box requires positive dimensions, a contained radius and 2–12 segments")
    half = tuple(size / 2 for size in size_m)
    radius = corner_radius_m

    def samples(axis: int) -> tuple[float, ...]:
        extent = half[axis]
        return tuple((-extent + radius * step / corner_segments)
                     for step in range(corner_segments + 1)) + tuple(
                     (extent - radius + radius * step / corner_segments)
                     for step in range(corner_segments + 1))

    # (fixed axis, direction, U axis, V axis); U x V points outward.
    orientations = ((0, 1, 1, 2), (0, -1, 2, 1),
                    (1, 1, 2, 0), (1, -1, 0, 2),
                    (2, 1, 0, 1), (2, -1, 1, 0))
    vertices: list[Vec3] = []
    indexes: dict[tuple[float, float, float], int] = {}
    faces: list[tuple[int, ...]] = []
    for fixed, direction, u_axis, v_axis in orientations:
        grid: list[list[int]] = []
        for v in samples(v_axis):
            row = []
            for u in samples(u_axis):
                outer = [0.0, 0.0, 0.0]
                outer[fixed] = direction * half[fixed]
                outer[u_axis], outer[v_axis] = u, v
                inner = [max(-half[i] + radius, min(half[i] - radius, outer[i]))
                         for i in range(3)]
                offset = [outer[i] - inner[i] for i in range(3)]
                distance = math.sqrt(sum(delta * delta for delta in offset))
                vertex = tuple(inner[i] + radius * offset[i] / distance for i in range(3))
                # The same edge is generated by adjacent face grids; weld it.
                key = tuple(round(value, 12) for value in vertex)
                if key not in indexes:
                    indexes[key] = len(vertices)
                    vertices.append(vertex)
                row.append(indexes[key])
            grid.append(row)
        for j in range(len(grid) - 1):
            for i in range(len(grid[j]) - 1):
                faces.append((grid[j][i], grid[j][i+1],
                              grid[j+1][i+1], grid[j+1][i]))
    return Mesh(tuple(vertices), tuple(faces))


def mitered_panel_rails(size_m: tuple[float, float], trim_width_m: float,
                        depth_m: float) -> tuple[tuple[str, Mesh], ...]:
    """Four independent closed solids around a genuine rectangular opening.

    The rails touch along 45-degree miter seams and have no hidden panel fill.
    The frame is centered in local XY and extrudes along local +Z.
    """
    if (len(size_m) != 2 or any(not math.isfinite(v) or v <= 0 for v in size_m) or
            not math.isfinite(trim_width_m) or trim_width_m <= 0 or
            trim_width_m >= min(size_m) / 2 or
            not math.isfinite(depth_m) or depth_m <= 0):
        raise GeometryError("Panel frame requires positive dimensions, trim and depth")
    w, h = (dim / 2 for dim in size_m)
    t = trim_width_m
    profiles = {
        "top": ((-w, h), (w, h), (w-t, h-t), (-w+t, h-t)),
        "right": ((w, h), (w, -h), (w-t, -h+t), (w-t, h-t)),
        "bottom": ((w, -h), (-w, -h), (-w+t, -h+t), (w-t, -h+t)),
        "left": ((-w, -h), (-w, h), (-w+t, h-t), (-w+t, -h+t)),
    }
    return tuple((label, extrude_profile(profile, depth_m))
                 for label, profile in profiles.items())


def fastener_head_mesh(style: str, radius_m: float, height_m: float) -> Mesh:
    """Capped domed-button or six-sided hex machine head (local +Z outward)."""
    if (not math.isfinite(radius_m) or radius_m <= 0 or
            not math.isfinite(height_m) or height_m <= 0):
        raise GeometryError("Fastener heads require positive radius and height")
    if style == "hex":
        sides = 6
        profile = ((radius_m, 0.0), (radius_m, height_m * 0.78),
                   (radius_m * 0.88, height_m))
    elif style == "button":
        sides = 32
        profile = ((radius_m, 0.0), (radius_m, height_m * 0.22),
                   (radius_m * 0.92, height_m * 0.54),
                   (radius_m * 0.72, height_m * 0.82),
                   (radius_m * 0.38, height_m))
    else:
        raise GeometryError(f"Unknown fastener head style: {style}")
    vertices = tuple((radius * math.cos(math.tau * i / sides),
                      radius * math.sin(math.tau * i / sides), z)
                     for radius, z in profile for i in range(sides))
    faces: list[tuple[int, ...]] = [tuple(reversed(range(sides)))]
    for ring in range(len(profile) - 1):
        for i in range(sides):
            j = (i + 1) % sides
            a, b = ring * sides, (ring + 1) * sides
            faces.append((a+i, a+j, b+j, b+i))
    last = (len(profile) - 1) * sides
    faces.append(tuple(last + i for i in range(sides)))
    return Mesh(vertices, tuple(faces))


_AXIS_FRAMES: dict[str, tuple[Vec3, Vec3, Vec3]] = {
    "+x": ((0, 1, 0), (0, 0, 1), (1, 0, 0)),
    "-x": ((0, -1, 0), (0, 0, 1), (-1, 0, 0)),
    "+y": ((0, 0, 1), (1, 0, 0), (0, 1, 0)),
    "-y": ((1, 0, 0), (0, 0, 1), (0, -1, 0)),
    "+z": ((1, 0, 0), (0, 1, 0), (0, 0, 1)),
    "-z": ((1, 0, 0), (0, -1, 0), (0, 0, -1)),
}


def detail_frame(axis: str) -> tuple[Vec3, Vec3, Vec3]:
    """Right-handed local coordinate frame for oriented surface detailing."""
    return _AXIS_FRAMES[axis]
